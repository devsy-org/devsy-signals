// Command gendepthschema writes the JSON Schema for the envelope nesting limit.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/devsy-org/devsy-signals/schema"
)

func main() {
	root := flag.String("root", "..", "repository root")
	flag.Parse()
	path := filepath.Join(*root, "schema", "record-depth.schema.json")
	if err := os.WriteFile(path, renderDepth(), 0o600); err != nil {
		fmt.Fprintln(os.Stderr, "gendepthschema:", err)
		os.Exit(1)
	}
}

func renderDepth() []byte {
	out := fmt.Appendf(nil, `{
  "$schema": "https://json-schema.org/draft/2020-12/schema",
  "$id": "https://github.com/devsy-org/devsy-signals/schema/record-depth.schema.json",
  "$comment": "Generated by gendepthschema. Do not edit.",
  "$ref": "#/$defs/level%d",
  "$defs": {
    "level0": {"not": {"type": ["array", "object"]}}`, schema.MaxRecordDepth)
	for level := 1; level <= schema.MaxRecordDepth; level++ {
		out = fmt.Appendf(out, ",\n    "+
			`"level%d": {"additionalProperties": {"$ref": "#/$defs/level%d"}, "items": {"$ref": "#/$defs/level%d"}}`,
			level, level-1, level-1)
	}
	return append(out, "\n  }\n}\n"...)
}
