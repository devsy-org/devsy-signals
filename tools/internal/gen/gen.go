// Package gen renders the Go and TypeScript code tables from the registry.
package gen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
	"text/template"

	"github.com/devsy-org/devsy-signals/tools/internal/registry"
)

const sourcePath = "schema/errors.yaml"

type classView struct {
	Const string
	Name  string
	Exit  int
}

type codeView struct {
	Const     string
	Code      string
	Class     string
	ClassName string
	Retryable bool
	Exit      int
	Summary   string
}

type view struct {
	Source  string
	Classes []classView
	Codes   []codeView
}

// Render returns the generated Go source and TypeScript source.
func Render(f registry.File) (goSrc, tsSrc []byte, err error) {
	v, err := newView(f)
	if err != nil {
		return nil, nil, err
	}
	raw, err := execute(parse("go", goTmplText, strconv.Quote), v)
	if err != nil {
		return nil, nil, err
	}
	goSrc, err = format.Source(raw)
	if err != nil {
		return nil, nil, fmt.Errorf("format generated Go: %w", err)
	}
	tsSrc, err = execute(parse("ts", tsTmplText, quoteJSON), v)
	return goSrc, tsSrc, err
}

func newView(f registry.File) (view, error) {
	v := view{Source: sourcePath}
	for name, exit := range f.Classes {
		v.Classes = append(
			v.Classes,
			classView{Const: "Class" + registry.ConstName(name), Name: name, Exit: exit},
		)
	}
	slices.SortFunc(v.Classes, func(a, b classView) int { return strings.Compare(a.Name, b.Name) })

	names := map[string]string{}
	for _, e := range f.Codes {
		c := codeView{
			Const: registry.ConstName(
				e.Code,
			),
			Code:      e.Code,
			Class:     e.Class,
			ClassName: "Class" + registry.ConstName(e.Class),
			Retryable: e.Retryable,
			Exit:      e.Exit,
			Summary:   e.Summary,
		}
		if other, dup := names[c.Const]; dup {
			return view{}, fmt.Errorf(
				"codes %q and %q both map to constant %s",
				other,
				e.Code,
				c.Const,
			)
		}
		names[c.Const] = e.Code
		v.Codes = append(v.Codes, c)
	}
	slices.SortFunc(v.Codes, func(a, b codeView) int { return strings.Compare(a.Code, b.Code) })
	return v, nil
}

func parse(name, text string, quote any) *template.Template {
	return template.Must(
		template.New(name).Funcs(template.FuncMap{"quote": quote}).Parse(text),
	)
}

func quoteJSON(s string) (string, error) {
	quoted, err := json.Marshal(s)
	if err != nil {
		return "", fmt.Errorf("quote TypeScript string: %w", err)
	}
	return string(quoted), nil
}

func execute(t *template.Template, v view) ([]byte, error) {
	var buf bytes.Buffer
	if err := t.Execute(&buf, v); err != nil {
		return nil, fmt.Errorf("render %s: %w", t.Name(), err)
	}
	return buf.Bytes(), nil
}

const goTmplText = `// Code generated by tools/cmd/gencodes from {{.Source}}; DO NOT EDIT.

package codes

// Class groups registered codes. Every class maps to one process exit code.
type Class string

// Error classes.
const (
{{- range .Classes}}
	{{.Const}} Class = {{quote .Name}}
{{- end}}
)

// Registered error codes.
const (
{{- range .Codes}}
	// {{.Const}}: {{.Summary}}
	{{.Const}} = {{quote .Code}}
{{- end}}
)

// Info is the registry entry for a code.
type Info struct {
	Class     Class
	Retryable bool
	Exit      int
	Summary   string
}

var classExit = map[Class]int{
{{- range .Classes}}
	{{.Const}}: {{.Exit}},
{{- end}}
}

var registry = map[string]Info{
{{- range .Codes}}
	{{.Const}}: {Class: {{.ClassName}}, Retryable: {{.Retryable}}, Exit: {{.Exit}}, Summary: {{quote .Summary}}},
{{- end}}
}

// Lookup returns the registry entry for code.
func Lookup(code string) (Info, bool) {
	info, ok := registry[code]
	return info, ok
}

// All returns every registered code in sorted order.
func All() []string {
	return []string{
{{- range .Codes}}
		{{.Const}},
{{- end}}
	}
}

// Known reports whether c is a registered class.
func (c Class) Known() bool {
	_, ok := classExit[c]
	return ok
}

// Exit returns the process exit code for c, or 1 for an unknown class.
func (c Class) Exit() int {
	if exit, ok := classExit[c]; ok {
		return exit
	}
	return 1
}
`

const tsTmplText = `// Code generated by tools/cmd/gencodes from {{.Source}}; DO NOT EDIT.

export const errorClasses = {
{{- range .Classes}}
  {{quote .Name}}: {{.Exit}},
{{- end}}
} as const;

export type ErrorClass = keyof typeof errorClasses;

export interface CodeInfo {
  readonly class: ErrorClass;
  readonly retryable: boolean;
  readonly exit: number;
  readonly summary: string;
}

export const codes = {
{{- range .Codes}}
  {{quote .Code}}: { class: {{quote .Class}}, retryable: {{.Retryable}}, exit: {{.Exit}}, summary: {{quote .Summary}} },
{{- end}}
} as const satisfies Record<string, CodeInfo>;

export type ErrorCode = keyof typeof codes;

export function lookupCode(code: string): CodeInfo | undefined {
  return Object.hasOwn(codes, code) ? codes[code as ErrorCode] : undefined;
}
`
